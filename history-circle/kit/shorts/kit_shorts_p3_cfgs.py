def capsin(rs,hi=None):
    out=[]
    for a,b,t in CAPS:
        for r0,r1 in rs:
            if a>=r0-0.15 and b<=r1+0.3: out.append((max(a,r0),min(b,r1),hi(t) if hi else t)); break
    return out
